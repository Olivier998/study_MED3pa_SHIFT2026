"""
Collect the MED3pa profiles and their explanations (Detectron decision and
p-value, FeatureResumer summary) from the profile trees generated by
experiments/main.py into a single CSV.

For each experiment folder, the most recent profiles_*.html file is used.

Usage (from the repository root):
    python -m experiments.extract_profiles [--results-dir DIR] [--output CSV]
"""

import argparse
from pathlib import Path

import pandas as pd

from src.profiles import read_tree_nodes, summarize_node


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results-dir", default="experiments/results")
    parser.add_argument("--output", default="experiments/results/profiles.csv")
    args = parser.parse_args()

    rows = []
    for run_dir in sorted(p for p in Path(args.results_dir).glob("*/*") if p.is_dir()):
        trees = sorted(run_dir.glob("profiles_*.html"))
        if not trees:
            continue
        task, criterion = run_dir.parent.name, run_dir.name
        nodes = read_tree_nodes(trees[-1])
        print(f"{task}/{criterion}: {len(nodes)} profiles ({trees[-1].name})")
        rows += [{"task": task, "criterion": criterion, **summarize_node(node), "file": trees[-1].name}
                 for node in nodes]

    pd.DataFrame(rows).to_csv(args.output, index=False)
    print(f"Saved {len(rows)} profiles to {args.output}")


if __name__ == "__main__":
    main()
